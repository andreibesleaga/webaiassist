// What the exported file says about who wrote it.
import { beforeEach, describe, expect, it } from 'vitest';
import { startPanel } from '../../src/ui/panel-controller';
import { answer } from '../helpers';
import { byId, click, loadPage, tick } from './dom';
import { fakeDeps } from './panel-fakes';

async function settle(): Promise<void> {
  for (let i = 0; i < 10; i += 1) await tick();
}

async function ask(text: string): Promise<void> {
  byId<HTMLTextAreaElement>('question').value = text;
  byId<HTMLFormElement>('ask').requestSubmit();
  await settle();
}

describe('the export mark', () => {
  beforeEach(() => {
    loadPage('sidepanel.html');
  });

  it('marks the export as written by the endpoint host, not by a local model (audit L4)', async () => {
    const deps = fakeDeps([answer('Done.')]);
    deps.settings = {
      ...deps.settings,
      runtime: 'endpoint',
      endpoint: { ...deps.settings.endpoint, url: 'https://api.example.com/v1', model: 'big' },
    };
    await startPanel(deps);
    click('start');
    await settle();
    await ask('hello');
    click('export');
    const text = deps.downloads[0]?.text ?? '';
    expect(text).toContain('Generated by an AI model at api.example.com');
    expect(text).not.toContain('local AI model');
    expect(text.startsWith('---\nai-generated: true\n')).toBe(true);
    expect(text).toMatch(/generator: "WebAIAssist \d/);
  });
});
