import { describe, expect, it } from 'vitest';
import { exportMarkdown, redactArgs } from '../../src/core/export';
import type { TranscriptEntry } from '../../src/core/export';

const meta = {
  origin: 'https://node.example',
  at: '2026-01-15T10:00:00.000Z',
  model: 'Qwen3',
  version: '0.1.0',
};

describe('redactArgs', () => {
  it('hides values of keys that look like secrets, at any depth', () => {
    const args = {
      query: 'x',
      apiKey: 'k',
      nested: { Password: 'p', ok: 1 },
      list: [{ token: 't' }],
    };
    expect(redactArgs(args)).toEqual({
      query: 'x',
      apiKey: '[redacted]',
      nested: { Password: '[redacted]', ok: 1 },
      list: [{ token: '[redacted]' }],
    });
  });
});

describe('exportMarkdown', () => {
  const entries: TranscriptEntry[] = [
    { kind: 'user', text: 'Propose a task' },
    { kind: 'tool-call', name: 'propose', args: { slug: 'a', secret: 's3' } },
    { kind: 'tool-result', name: 'propose', ok: true, text: '{"trust":"untrusted","x":"```"}' },
    { kind: 'tool-denied', name: 'remember' },
    { kind: 'error', text: 'Stopped.' },
    { kind: 'answer', text: 'Here is the payload.' },
  ];

  it('writes a heading with the site, time and model', () => {
    const md = exportMarkdown(entries, meta);
    expect(md).toMatch(/\n# WebAIAssist conversation\n/);
    expect(md).toContain('- Site: https://node.example');
    expect(md).toContain('- Exported: 2026-01-15T10:00:00.000Z');
    expect(md).toContain('- Model: Qwen3');
  });

  it('says in the header that a local AI model wrote it (F14.8)', () => {
    const md = exportMarkdown(entries, meta);
    expect(md).toContain('Generated by a local AI model through WebAIAssist');
    expect(md.indexOf('Generated by a local AI model')).toBeLessThan(md.indexOf('## You'));
  });

  it('starts with a machine-readable AI mark (audit L4)', () => {
    const md = exportMarkdown(entries, meta);
    expect(md.startsWith('---\nai-generated: true\n')).toBe(true);
    expect(md).toContain('generator: "WebAIAssist 0.1.0"');
    expect(md).toContain('model: "Qwen3"');
    expect(md).toContain('runs-on: "this computer"');
    expect(md.indexOf('\n---\n')).toBeLessThan(md.indexOf('# WebAIAssist conversation'));
  });

  it('names the endpoint host and not "local" when an endpoint wrote the answers (audit L4)', () => {
    const md = exportMarkdown(entries, { ...meta, remote: 'api.example' });
    expect(md).toContain('Generated by an AI model at api.example through WebAIAssist');
    expect(md).not.toContain('local AI model');
    expect(md).toContain('runs-on: "api.example"');
  });

  it('writes a model name with quotes or a line break as one quoted value', () => {
    const md = exportMarkdown([], { ...meta, model: 'a"b\nc: d' });
    expect(md).toContain('model: "a\\"b\\nc: d"');
    expect(md.split('\n---\n')[0]).not.toContain('\nc: d');
  });

  it('keeps the user text, the answer, the denial and the error', () => {
    const md = exportMarkdown(entries, meta);
    expect(md).toContain('## You\n\nPropose a task');
    expect(md).toContain('## WebAIAssist\n\nHere is the payload.');
    expect(md).toContain('You denied the call to `remember`.');
    expect(md).toContain('Error: Stopped.');
  });

  it('writes the loop’s notes as notes, with Markdown characters escaped', () => {
    const md = exportMarkdown([{ kind: 'note', text: 'It was *stopped* [here](x).' }], meta);
    expect(md).toContain('Note: It was \\*stopped\\* \\[here\\]\\(x\\).');
  });

  it('shows tool arguments without secrets and marks results as untrusted', () => {
    const md = exportMarkdown(entries, meta);
    expect(md).not.toContain('s3');
    expect(md).toContain('"secret": "[redacted]"');
    expect(md).toContain('Result of `propose` (untrusted content from the page)');
  });

  it('fences results with a fence longer than any run of backticks inside', () => {
    const md = exportMarkdown(entries, meta);
    expect(md).toContain('````text\n{"trust":"untrusted","x":"```"}\n````');
  });

  it('says when a tool failed', () => {
    const md = exportMarkdown([{ kind: 'tool-result', name: 'read', ok: false, text: 'no' }], meta);
    expect(md).toContain('Result of `read` (failed; untrusted content from the page)');
  });
});

describe('exportMarkdown: steered text stays text', () => {
  it('escapes images, links and HTML in answers and errors', () => {
    const md = exportMarkdown(
      [
        { kind: 'answer', text: '![x](https://evil.example/p) <img src=x> [a](http://b)' },
        { kind: 'error', text: '![e](https://evil.example/e)' },
      ],
      {
        origin: 'https://node.example',
        at: '2026-01-15T10:00:00.000Z',
        model: 'm',
        version: '0.1.0',
      },
    );
    expect(md).not.toMatch(/!\[[^\]]*\]\(/);
    expect(md).not.toMatch(/\]\(https?:/);
    expect(md).not.toMatch(/(^|[^\\])<img/);
    expect(md).toContain('\\<img src=x\\>');
    expect(md).toContain('\\!\\[x\\]\\(https://evil.example/p\\)');
  });

  it('quotes tool names safely in code spans', () => {
    const md = exportMarkdown([{ kind: 'tool-denied', name: 'a`b](x)' }], {
      origin: 'o',
      at: 'a',
      model: 'm',
      version: '0.1.0',
    });
    expect(md).toContain('You denied the call to `a_b__x_`.');
  });
});
