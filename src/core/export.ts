// Export: the conversation as Markdown for the user to keep, marked as AI-generated in a
// front-matter block and in a sentence. Values of argument keys
// that look like secrets are hidden, and so is every copy of a known secret (the endpoint
// API key) anywhere in the text; tool results are labelled as untrusted page content.
// Model answers and errors can be steered by a page, so they are written with Markdown's
// active characters escaped: a viewer shows them as text and loads no image or link.
import type { LoopEvent } from './ports/chat-ui';
import { quoteName } from './sanitize';
import type { ToolArgs } from './types';

/** One line of the transcript: the user's text or an event of the agent loop. */
export type TranscriptEntry = { readonly kind: 'user'; readonly text: string } | LoopEvent;

export interface ExportMeta {
  readonly origin: string;
  readonly at: string;
  readonly model: string;
  /** The extension version, for the machine-readable mark. */
  readonly version: string;
  /** The host the chat went to when the model is a remote endpoint; absent for a local model. */
  readonly remote?: string;
  /** Values that must not appear in the file, such as the endpoint API key. */
  readonly secrets?: readonly string[];
}

const SECRET_KEY =
  /pass(word)?|secret|token|api[-_]?key|auth|bearer|private[-_]?key|cookie|session|credential/i;
/** What redactArgs writes for a value whose key looks secret. */
export const REDACTED = '[redacted]';
/** What the activity trace writes where it removed a known secret (the API key) from a text. */
export const REMOVED = '[removed]';
/** Shorter values would hide ordinary words. */
const MIN_SECRET_LENGTH = 8;

export function redactArgs(value: unknown): unknown {
  if (Array.isArray(value)) return value.map(redactArgs);
  if (typeof value !== 'object' || value === null) return value;
  return Object.fromEntries(
    Object.entries(value).map(([key, item]) => [
      key,
      SECRET_KEY.test(key) ? REDACTED : redactArgs(item),
    ]),
  );
}

/** Text shown as written: no image, link, HTML, heading or emphasis in a Markdown viewer. */
export function escapeMarkdown(text: string): string {
  return text.replace(/[\\`*_[\]()!<>#|~]/g, '\\$&');
}

/** A fence one backtick longer than the longest run inside the text (at least three). */
function fenced(text: string, info: string): string {
  const longest = Math.max(2, ...(text.match(/`+/g) ?? []).map((run) => run.length));
  const fence = '`'.repeat(longest + 1);
  return `${fence}${info}\n${text}\n${fence}`;
}

function argsBlock(name: string, args: ToolArgs): string {
  const json = JSON.stringify(redactArgs(args), null, 2);
  return `Tool call: \`${quoteName(name)}\`\n\n${fenced(json, 'json')}`;
}

function resultBlock(name: string, ok: boolean, text: string): string {
  const label = ok ? 'untrusted content from the page' : 'failed; untrusted content from the page';
  return `Result of \`${quoteName(name)}\` (${label}):\n\n${fenced(text, 'text')}`;
}

function entryBlock(entry: TranscriptEntry): string {
  switch (entry.kind) {
    case 'user':
      return `## You\n\n${entry.text}`;
    case 'answer':
      return `## WebAIAssist\n\n${escapeMarkdown(entry.text)}`;
    case 'tool-call':
      return argsBlock(entry.name, entry.args);
    case 'tool-result':
      return resultBlock(entry.name, entry.ok, entry.text);
    case 'tool-denied':
      return `You denied the call to \`${quoteName(entry.name)}\`.`;
    case 'error':
      return `Error: ${escapeMarkdown(entry.text)}`;
    case 'note':
      return `Note: ${escapeMarkdown(entry.text)}`;
  }
}

function hideSecrets(text: string, secrets: readonly string[]): string {
  return secrets
    .filter((secret) => secret.length >= MIN_SECRET_LENGTH)
    .reduce((out, secret) => out.split(secret).join(REDACTED), text);
}

/** The sentence that says who wrote the text (EU AI Act, Article 50: the mark is not local
 *  when an endpoint wrote the answers). */
function generatedBy(meta: ExportMeta): string {
  const who = meta.remote ? `an AI model at ${meta.remote}` : 'a local AI model';
  return `Generated by ${who} through WebAIAssist. Answers can be wrong.`;
}

/** The machine-readable mark: a YAML block at the top, values quoted as JSON strings. */
function frontMatter(meta: ExportMeta): string {
  return [
    '---',
    'ai-generated: true',
    `generator: ${JSON.stringify(`WebAIAssist ${meta.version}`)}`,
    `model: ${JSON.stringify(meta.model)}`,
    `runs-on: ${JSON.stringify(meta.remote ?? 'this computer')}`,
    '---',
  ].join('\n');
}

export function exportMarkdown(entries: readonly TranscriptEntry[], meta: ExportMeta): string {
  const head = [
    frontMatter(meta),
    '',
    '# WebAIAssist conversation',
    '',
    generatedBy(meta),
    '',
    `- Site: ${meta.origin}`,
    `- Exported: ${meta.at}`,
    `- Model: ${meta.model}`,
  ].join('\n');
  const text = `${[head, ...entries.map(entryBlock)].join('\n\n')}\n`;
  return hideSecrets(text, meta.secrets ?? []);
}
