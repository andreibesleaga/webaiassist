// Writes src/protocol/validators.generated.js: the message schemas compiled by Ajv ahead
// of time ("standalone" code). Extension pages and service workers run under a CSP that
// forbids `new Function`, so Ajv cannot compile there at runtime; this code needs no eval.
// Run: npm run gen:validators. A unit test fails when the committed file is stale.
import { Ajv } from 'ajv';
import standaloneCode from 'ajv/dist/standalone/index.js';
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { ENVELOPE_SCHEMA, MESSAGE_SCHEMAS } from '../src/protocol/schemas.ts';

export const OUTPUT = fileURLToPath(
  new URL('../src/protocol/validators.generated.js', import.meta.url),
);
export const TYPES_OUTPUT = OUTPUT.replace(/\.js$/, '.d.ts');

const HEADER =
  '// SPDX-License-Identifier: Apache-2.0\n' +
  '// Generated by scripts/gen-validators.ts from src/protocol/schemas.ts. Do not edit.\n';

function keys(): string[] {
  return ['envelope', ...Object.keys(MESSAGE_SCHEMAS)];
}

/** 'tools/list-result' -> 'validate_tools_list_result' */
export function exportName(key: string): string {
  return `validate_${key.replace(/[^a-z0-9]/gi, '_')}`;
}

export function generateValidatorSource(): string {
  // `unicode: false` makes maxLength count UTF-16 units with `.length`, so the code needs
  // no Ajv runtime helper (a `require`). Ajv marks the option deprecated but honours it;
  // `logger: false` silences that notice. A unit test checks the output has no `require(`.
  const ajv = new Ajv({ code: { source: true, esm: true }, unicode: false, logger: false });
  const exports: Record<string, string> = {};
  const schemas: Record<string, object> = { envelope: ENVELOPE_SCHEMA, ...MESSAGE_SCHEMAS };
  for (const key of keys()) {
    ajv.addSchema(schemas[key] ?? {}, key);
    exports[exportName(key)] = key;
  }
  return HEADER + standaloneCode(ajv, exports) + '\n';
}

export function generateTypesSource(): string {
  const lines = keys().map(
    (key) => `export declare const ${exportName(key)}: StandaloneValidator;`,
  );
  return (
    HEADER +
    'export interface StandaloneValidator {\n' +
    '  (data: unknown): boolean;\n' +
    '  errors?: { instancePath: string; message?: string }[] | null;\n' +
    '}\n' +
    lines.join('\n') +
    '\n'
  );
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  writeFileSync(OUTPUT, generateValidatorSource());
  writeFileSync(TYPES_OUTPUT, generateTypesSource());
  console.log(`wrote ${OUTPUT} and ${TYPES_OUTPUT}`);
}
